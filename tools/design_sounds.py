"""Render the launcher's sounds (design/feedback.md, Sound) into launcher/sounds.c.

The recipes are the table in feedback.md: short, dry and quiet, 16-bit mono.
They are rendered at the rate the unit's mixer runs at, and at LEVEL_DB below
full scale, so they sit under whatever is playing without ducking it.

  tools/design_sounds.py           write launcher/sounds.c
  tools/design_sounds.py --check   fail if the committed file is out of date
  tools/design_sounds.py --wav DIR also write one .wav per sound, to listen to
"""
import math
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "launcher/sounds.c"
RATE = 48000        # dmix's own rate on the unit (stock asound.conf sets none)
LEVEL_DB = -18.0    # "about 18 dB below the current listening level"
PEAK = 32767 * 10 ** (LEVEL_DB / 20)
# The order of enum ui_sound in launcher/ui/screens.h.
ORDER = ("tick", "key", "bump", "select", "back", "on", "off", "deny", "connected", "lost")


def tone(freq, ms, decay_ms=None, attack_ms=0.0, to_freq=None, shape="sine"):
    """One note: a sine (or triangle), optionally gliding, with an exponential
    decay; the last 2 ms are faded so that it never ends on a click."""
    n = int(RATE * ms / 1000)
    out, phase = [], 0.0
    for i in range(n):
        t = i / RATE
        f = freq if to_freq is None else freq + (to_freq - freq) * i / n
        phase += 2 * math.pi * f / RATE
        v = math.sin(phase) if shape == "sine" else 2 / math.pi * math.asin(math.sin(phase))
        if decay_ms:
            v *= math.exp(-t * 1000 / decay_ms)
        if attack_ms:
            v *= min(1.0, t * 1000 / attack_ms)
        v *= min(1.0, (n - i) / (RATE * 0.002))
        out.append(v)
    return out


def silence(ms):
    return [0.0] * int(RATE * ms / 1000)


def recipes():
    tick = tone(1800, 15, decay_ms=4)
    return {
        "tick": tick,
        "key": tick,
        "bump": tone(160, 70, decay_ms=25, to_freq=90),
        "select": tone(660, 30, decay_ms=14) + tone(990, 60, decay_ms=22),
        "back": tone(990, 30, decay_ms=14) + tone(660, 60, decay_ms=22),
        "on": tone(990, 60, decay_ms=20),
        "off": tone(660, 60, decay_ms=20),
        "deny": tone(200, 40, decay_ms=30, shape="triangle") + silence(50) + tone(200, 40, decay_ms=30, shape="triangle"),
        "connected": tone(660, 160, decay_ms=90, attack_ms=10) + tone(880, 160, decay_ms=110, attack_ms=10),
        "lost": tone(880, 160, decay_ms=90, attack_ms=10) + tone(660, 160, decay_ms=110, attack_ms=10),
    }


def pcm(samples):
    return [max(-32768, min(32767, int(round(v * PEAK)))) for v in samples]


def render():
    r = recipes()
    lines = ["/* SPDX-License-Identifier: MIT",
             " * The launcher's sounds (design/feedback.md): generated by tools/design_sounds.py;",
             f" * do not edit. 16-bit mono at {RATE} Hz, {LEVEL_DB:g} dB below full scale.",
             " */",
             '#include "sounds.h"',
             ""]
    for name in ORDER:
        if name == "key":
            continue    # the tick's sample
        data = pcm(r[name])
        lines.append(f"static const int16_t {name}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            lines.append("\t" + ", ".join(str(v) for v in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append(f"const int sound_rate = {RATE};")
    lines.append("")
    lines.append("/* In the order of enum ui_sound. */")
    lines.append("const struct sound sounds[SOUNDS] = {")
    for name in ORDER:
        src = "tick" if name == "key" else name
        lines.append(f"\t{{ {src}, sizeof({src}) / sizeof({src}[0]) }},\t/* {name}: {len(r[name]) * 1000 // RATE} ms */")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--wav" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--wav") + 1])
        out.mkdir(parents=True, exist_ok=True)
        for name, samples in recipes().items():
            with wave.open(str(out / f"{name}.wav"), "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(RATE)
                w.writeframes(struct.pack(f"<{len(samples)}h", *pcm(samples)))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run tools/design_sounds.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
